import pandas as pd
from pydeseq2.dds import DeseqDataSet

# Standardize metadata index and values
metadata_compat = metadata.copy()
metadata_compat.index = list(metadata_compat.index.map(str))
metadata_compat = metadata_compat.astype(object)

dds = DeseqDataSet(
    counts=filtered_count,
    metadata=metadata_compat,
    design_factors="Condition",
    n_cpus=4,
)

dds.deseq2()

from pydeseq2.default_inference import DefaultInference
from pydeseq2.ds import DeseqStats

inference = DefaultInference()

stats_res = DeseqStats(
    dds,
    contrast = ["Condition","Pre_ADT","Post_ADT"
    ],
    inference = inference

)

stats_res.summary()

results_df = stats_res.results_df.copy()

results_df.head()

import mygene

# Define sig_degs by filtering results_df for statistically significant genes (padj < 0.05)
sig_degs = results_df[results_df["padj"] < 0.05].copy()

mg = mygene.MyGeneInfo()
gene_ids = sig_degs.index.astype(str).tolist()
mapped = mg.querymany(gene_ids, scopes="entrezgene", fields="symbol", species="human", as_dataframe=True)

sig_degs["Symbol"] = mapped["symbol"].groupby(level=0).first()
display(sig_degs[["Symbol", "log2FoldChange", "padj"]].head(10))

sig_degs.to_csv("sig_degs_training.csv", index = True)

# Use correct element-wise pandas boolean operations with '&' and parenthesized conditions
