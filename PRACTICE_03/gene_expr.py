from matplotlib import pyplot as plt
import seaborn as sns
import numpy as np

# Create a categorical column for classification
sig_degs = sig_degs.copy()
sig_degs["Expression"] = "Not Significant"
sig_degs.loc[(sig_degs["log2FoldChange"] >= 1) & (sig_degs["padj"] < 0.05), "Expression"] = "Upregulated"
sig_degs.loc[(sig_degs["log2FoldChange"] <= -1) & (sig_degs["padj"] < 0.05), "Expression"] = "Downregulated"

# Calculate -log10 of padj for standard volcano plot y-axis
sig_degs["-log10_padj"] = -np.log10(sig_degs["padj"])

plt.figure(figsize=(10, 6))
colors = {"Upregulated": "green", "Downregulated": "red", "Not Significant": "grey"}

sns.scatterplot(
    data=sig_degs,
    x="log2FoldChange",
    y="-log10_padj",
    hue="Expression",
    palette=colors,
    alpha=0.8
)

plt.title("Volcano Plot of Differentially Expressed Genes")
plt.xlabel("log2 Fold Change")
plt.ylabel("-log10 Adjusted P-value")
plt.axhline(-np.log10(0.05), color="black", linestyle="--", label="padj = 0.05")
plt.axvline(1, color="black", linestyle="--")
plt.axvline(-1, color="black", linestyle="--")
plt.legend()
plt.show()
